"""SpecStory: chat histories SpecStory saves under `.specstory/history/` and its users commit to public repositories.

Found by code search for `path:.specstory/history`; each repository found is read whole from its default branch, so
files code search cannot see (over 384 KB, 14% of files measured on 2026-10-03) are kept too. One row per file.

The file's own header names the agent and the session (measured on 2026-10-03): `<!-- Claude Code Session <uuid>
(<time>) -->`, `<!-- Codex CLI Session ... -->`, `<!-- Gemini CLI Session ... -->`, `<!-- Visual Studio Code
Session ... -->`; older files (Cursor, and Visual Studio Code before the CLI) carry only `<!-- Generated by
SpecStory -->`. Blocks open `_**User ...**_`, `_**Agent (<model> <time>)**_` or `_**Assistant (<model>/<mode>)**_`;
tool calls are `<tool-use>` blocks.
"""

from __future__ import annotations

import re
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

from ..facts import FACTS_VERSION
from ..model import RawFile, Session
from ..util import append_jsonl
from ..repos import by_current, current, once
from . import Context
from .entire import namespace
from .github_files import politely, read_repo, search_files, search_gaps, with_known

NAME = "specstory"
QUERY = "path:.specstory/history"
SESSION = re.compile(r"<!--\s*(.+?)\s+Session\s+([0-9A-Za-z][0-9A-Za-z_-]{7,})\s*(?:\(([^)]*)\))?\s*-->")
# The header's agent names, as SpecStory writes them (measured: "Cursor IDE", "cursoride", "VS Code Copilot IDE",
# "vscode" ...), to one name per agent; keyed with spaces and punctuation removed.
AGENTS = {"claudecode": "Claude Code", "codexcli": "Codex", "codex": "Codex", "geminicli": "Gemini CLI",
          "visualstudiocode": "VS Code Copilot", "vscode": "VS Code Copilot", "vscodecopilot": "VS Code Copilot",
          "vscodecopilotide": "VS Code Copilot", "cursor": "Cursor", "cursoride": "Cursor", "cursorcli": "Cursor CLI",
          "droid": "Factory Droid", "factorydroid": "Factory Droid", "pi": "Pi", "opencode": "OpenCode"}


def agent_name(raw: str) -> str:
    key = re.sub(r"[^a-z0-9]", "", raw.lower())
    return AGENTS.get(key, raw.strip())
HEAD = re.compile(r"^_\*\*(User|Agent|Assistant)\b([^*]*)\*\*_\s*$", re.M)
HIDDEN = re.compile(r"<(tool-use|details|think)\b.*?</\1>", re.S)
NAME_TIME = re.compile(r"(\d{4}-\d{2}-\d{2})_(\d{2})-(\d{2})(?:-(\d{2}))?(Z)?")


def in_history(path: str) -> bool:
    """A chat history SpecStory saved: a Markdown file under `.specstory/history/`. Not a macOS AppleDouble (`._x.md`)
    or any other hidden file, and not the JSON or notes that share the folder (40 such files had no conversation in
    them, 2026-10-05)."""
    parts = path.split("/")
    return (len(parts) >= 3 and parts[-3:-1] == [".specstory", "history"] and parts[-1].endswith(".md")
            and not parts[-1].startswith("."))


def facts(text: str, filename: str) -> dict:
    """Counts and times from a SpecStory file. `n_user_messages` is None: SpecStory's user blocks are the prompts as
    it rendered them, and nothing marks text the tool inserted apart."""
    m = SESSION.search(text[:4000])
    agent = agent_name(m[1]) if m else None
    heads = list(HEAD.finditer(text))
    users = agents = 0
    models = set()
    for i, h in enumerate(heads):
        body = text[h.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
        if h[1] == "User":
            users += 1
            continue
        mm = re.search(r"\(([^)\s/]+)", h[2])
        if mm and not re.match(r"\d", mm[1]):
            models.add(mm[1])
        if HIDDEN.sub("", body).strip():
            agents += 1
    # A time with a zone (the header's "...Z", a file name's "...Z") is given as UTC; one without a zone is local
    # to whoever saved it, so it is kept as written in source_facts and not as started_at.
    started, local = None, None
    raw = m[3].strip() if m and m[3] else None
    if not raw:
        t = NAME_TIME.search(filename)
        if t:
            raw = f"{t[1]}T{t[2]}:{t[3]}:{t[4] or '00'}" + ("Z" if t[5] else "")
    if raw:
        if raw.endswith(("Z", "z")) or re.search(r"[+-]\d{2}:?\d{2}$", raw):
            from ..facts import _iso

            started = _iso(raw.replace(" ", "T", 1))
        else:
            local = raw
    return {"agent": agent, "session_id": m[2] if m else None, "local_time": local, "facts": {
        "n_user_entries": users, "n_user_messages": None, "n_agent_messages": agents,
        "n_tool_calls": len(re.findall(r"<tool-use\b", text)), "has_tool_results": None,
        "has_timestamps": bool(started), "started_at": started, "ended_at": None, "models": sorted(models),
        "agent_version": None}}


def row_facts(row: dict) -> dict:
    """A stored row's counts from its file (for counting again with a newer parser); runs in the process pool."""
    from pathlib import Path

    local = Path(row["files"][0]["local"])
    if not local.exists():
        return {"skip": "its file is gone; counted again once fetched again"}
    got = facts(local.read_text(errors="replace"), Path(row["files"][0]["path"]).name)
    return {**got["facts"], "extra_update": {"local_time": got["local_time"]}}


def run(ctx: Context) -> dict:
    if ctx.only:
        repos = sorted(set(ctx.only))
        found_urls = {}
    elif ctx.github is None:
        ctx.log("specstory: no GitHub token and no --only: nothing to read")
        return {"repos": 0, "sessions": 0, "new": 0, "changed": 0, "same": 0}
    else:
        items = search_files(ctx, NAME, QUERY)
        repos = sorted({i["repo"] for i in items})
        found_urls = {(i["repo"], i["path"]): i["url"] for i in items}
        ctx.log(f"specstory: code search found {len(items):,} files in {len(repos):,} repositories")
        repos = with_known(ctx, NAME, repos)
    if ctx.limit:
        repos = repos[:ctx.limit]
    if ctx.dry_run:
        return {"repos": len(repos)}
    meta = by_current(ctx.github.repo_meta(repos)) if ctx.github else {}
    repos = once(meta, repos)   # a renamed repository answers to its old name too: read once, under its current one
    found_urls = {(current(meta, r), path): u for (r, path), u in found_urls.items()}
    stats = {"repos": len(repos), "sessions": 0, "new": 0, "changed": 0, "same": 0, "errors": 0, "beyond_search": 0,
             "search": search_gaps(ctx, NAME, QUERY) if not ctx.only else None}

    def one(repo: str) -> list[dict]:
        head, files = politely(read_repo, ctx, NAME, repo, in_history)
        rows = []
        for path, (oid, local) in files.items():
            if not local.exists():
                continue
            text = local.read_text(errors="replace")
            got = facts(text, Path(path).name)
            m = meta.get(repo) or {}
            session = Session(
                source=NAME, source_id=f"{repo}:{path}", files=[RawFile.at(path, local)],
                found_url=found_urls.get((repo, path)) or f"https://github.com/{repo}/blob/{head}/{path}",
                found_commit=head, repo=repo, repo_url=m.get("repo_url") or f"https://github.com/{repo}",
                repo_license=m.get("repo_license"), repo_language=m.get("repo_language"), agent=got["agent"],
                file_format="markdown",
                dedup_key=f"{namespace(got['agent'])}:{got['session_id']}" if got["session_id"] and got["agent"] else None,
                facts=got["facts"], extra={"blob": oid, "found_by_search": (repo, path) in found_urls,
                                           "facts_version": FACTS_VERSION, "local_time": got["local_time"]})
            rows.append(session.row())
        return rows

    with ThreadPoolExecutor(ctx.workers) as pool:
        futures = {pool.submit(one, r): r for r in repos}
        for fut in as_completed(futures):
            repo = futures[fut]
            try:
                rows = fut.result()
            except Exception as e:
                stats["errors"] += 1
                append_jsonl(ctx.config.state / NAME / "errors.jsonl", {"repo": repo, "error": f"{type(e).__name__}: {str(e)[-200:]}"})
                continue
            for row in rows:
                stats[ctx.ledger.upsert(row)] += 1
                stats["sessions"] += 1
                stats["beyond_search"] += not row["extra"]["found_by_search"]
    from .. import relabel

    stats["recounted"] = relabel.recount(ctx, NAME, row_facts)
    stats["relabeled"] = relabel.repos(ctx, NAME)
    return stats
