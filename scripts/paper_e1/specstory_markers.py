"""Read-only, counts only (2026-11-08): does SpecStory's export leave Claude Code's harness text out, or does our mark
miss it there? Claude Code's user role holds 39.5% program text in Entire's logs but 26.6% in SpecStory's exports
(m17j); SpecStory records no author, so the mark relies on rules there. For Claude Code's kept sessions by logger:
how many sessions hold, in any user-role row, each of a set of fixed texts Claude Code writes itself (local command
output, its caveat, system reminders, skill bodies, a continued session's summary, an interrupt), and of those rows
how many the mark calls typed. If SpecStory's sessions hold them about as often as Entire's and the mark calls them
typed, the mark misses them; if they seldom hold them at all, the export leaves them out.
VERSION_DIR=... python specstory_markers.py OUT.json   (SM_SAMPLE=20: a dry run)
"""
import json
import os
import sys

import duckdb

V = os.environ["VERSION_DIR"]
SAMPLE = int(os.environ.get("SM_SAMPLE", "0"))
OUT = sys.argv[1]
MARKERS = {"local command output": "<local-command-stdout>",
           "local command caveat": "Caveat: The messages below were generated by the user",
           "system reminder": "<system-reminder>",
           "skill body": "Base directory for this skill",
           "continued session": "This session is being continued from a previous conversation",
           "interrupt": "[Request interrupted by user",
           "slash command": "<command-name>"}
con = duckdb.connect()
con.execute("SET threads=8; SET memory_limit='28GB'; SET temp_directory='/path/to/pairlogs-work/tmp-sm'")
con.execute(f"""create temp table s as select session_key, source from read_parquet('{V}/data/*/*.parquet', union_by_name=true)
                where duplicate_of is null and agent = 'Claude Code'
                and source in ('entire', 'specstory', 'dataclaw', 'swe-chat-v2')
                {f"and hash(session_key) % {SAMPLE} = 0" if SAMPLE else ""}""")
cols = ", ".join(f"position({json.dumps(m)[1:-1]!r} in content) > 0 as m{i}" for i, m in enumerate(MARKERS.values()))
con.execute(f"""create temp table r as select c.session_key, s.source, coalesce(c.typed_by_developer, false) as typed, {cols}
                from read_parquet('{V}/conversations/*/*.parquet', union_by_name=true) c join s using (session_key)
                where c.role = 'user' and c.copy_of is null and c.content is not null""")
res = {"version": V, "sample_1_in": SAMPLE or 1, "by_source": {}}
for (src,) in con.execute("select distinct source from s order by 1").fetchall():
    ns = con.execute("select count(*) from s where source = ?", [src]).fetchone()[0]
    rows = con.execute("select count(*) from r where source = ?", [src]).fetchone()[0]
    d = {"sessions": ns, "user_rows": rows, "markers": {}}
    for i, name in enumerate(MARKERS):
        k_s, k_r, k_t = con.execute(f"""select count(distinct session_key) filter (where m{i}), count(*) filter (where m{i}),
                                           count(*) filter (where m{i} and typed) from r where source = ?""", [src]).fetchone()
        d["markers"][name] = {"sessions_with": k_s, "sessions_with_pct": round(100 * k_s / ns, 1) if ns else None,
                              "rows": k_r, "rows_marked_typed": k_t}
    res["by_source"][src] = d
assert res["by_source"], "no Claude Code session"
print(json.dumps(res, indent=1))
json.dump(res, open(OUT, "w"), indent=1)
